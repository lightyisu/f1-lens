/** 按当前语言返回大奖赛名称；中文附带赛道地名 */
export function localizeRaceName(
  raceName: string,
  circuitId: string,
  locale: Locale
): string {
  if (locale === "en") return raceName;
  const title =
    RACE_NAME_ZH[raceName] ??
    CIRCUIT_RACE_ZH[circuitId] ??
    raceName.replace(/\s+Grand Prix$/i, "大奖赛");
  const place = CIRCUIT_PLACE_ZH[circuitId];
  return place ? `${title}·${place}` : title;
}
